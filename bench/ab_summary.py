#!/usr/bin/env python3
"""The 0.1.43.1 / 0.1.44.1 A/B (bench/ab_versions.sh) in one table, from the raw result files.

  python3 -B bench/ab_summary.py v431-1 v441-1 v441pf v441-2 v431-2 > results/AB-0.1.44.1.md

Per run: the arm (engine, config), the PLE probe (three fresh ~16K-token prompts; the pool partition's physical reads
and the ARC's prefetch misses), the traced probe's system-call and ZFS function counts, and the perf set's headline
numbers (medians).  Every number is read from results/; nothing is typed in.
"""
from __future__ import annotations

import json
import re
import statistics
import sys
from pathlib import Path

R = Path(__file__).resolve().parents[1] / "results"


def jl(p: Path) -> list[dict]:
    return [json.loads(x) for x in p.read_text().splitlines() if x.strip()] if p.exists() else []


def med(xs):
    xs = [x for x in xs if isinstance(x, (int, float))]
    return round(statistics.median(xs), 1) if xs else None


def rng(xs, nd=1):
    xs = [x for x in xs if isinstance(x, (int, float))]
    if not xs:
        return "-"
    lo, hi = min(xs), max(xs)
    return f"{lo:.{nd}f}" if lo == hi else f"{lo:.{nd}f}-{hi:.{nd}f}"


def last(recs, tag, scen=None):
    """The newest record of `tag` (and `scen`): a scenario record's "result", a probe record itself."""
    m = [r for r in recs if r.get("tag") == tag and (scen is None or r.get("scenario") == scen)]
    return (m[-1]["result"] if scen else m[-1]) if m else None


def arm(tag: str) -> dict:
    t = (R / f"{tag}-arm.txt").read_text() if (R / f"{tag}-arm.txt").exists() else ""
    g = lambda pat: (re.search(pat, t) or [None, "?"])[1]   # noqa: E731
    return {"arm": g(r"arm (\w)"), "engine": g(r"session is up \(engine ([0-9.]+)\)"),
            "exe_sha": g(r"exe \S+ sha256 (\w+)"), "cfg_sha": g(r"config \S+ sha256 (\w+)"),
            "prefetch": "off" if "--no-ple-prefetch" in t else "on"}


def trace(tag: str) -> dict:
    p = R / f"{tag}-traced-trace.txt"
    if not p.exists():
        return {}
    t = p.read_text()
    out = {}
    for name in ("syscalls:sys_enter_madvise", "syscalls:sys_enter_fadvise64"):
        m = re.search(re.escape(name) + r"\s+(\d+)", t)
        out[name.split("_")[-1]] = int(m[1]) if m else None
    for fn in ("zpl_fadvise", "dmu_prefetch", "dbuf_prefetch", "vfs_fadvise"):
        m = re.search(rf"^{fn}\s+calls\s+(\d+)\s+total\s+([\d.]+) ms", t, re.M)
        out[fn] = (int(m[1]), float(m[2])) if m else (0, 0.0)
    out["tokens"] = sum(r.get("prompt_tokens") or 0 for r in (last(jl(R / "ple_prefetch_probe.jsonl"), f"{tag}-traced") or {}).get("rows", []))
    return out


def main() -> int:
    tags = sys.argv[1:]
    probes = jl(R / "ple_prefetch_probe.jsonl")
    stress, lat = jl(R / "stress.jsonl"), jl(R / "latency.jsonl")
    o = ["# Strata 0.1.43.1 vs 0.1.44.1 on this box (generated by bench/ab_summary.py)", "",
         "Every run is a fresh start of the server; same config except where the prefetch column says on (no "
         "`--no-ple-prefetch`).  Order of the runs: " + " -> ".join(tags) + ".", "",
         "## Fresh ~16K-token prompts (ple_prefetch_probe.py; untraced: the same three text slices as the earlier probes)", "",
         "| run | engine | PLE prefetch | prompt tok/s (engine) | TTFT s | pool partition reads GB per prompt | ARC prefetch misses per prompt |",
         "|---|---|---|---:|---:|---:|---:|"]
    for t in tags:
        a, p = arm(t), last(probes, t)
        rows = (p or {}).get("rows", [])
        o.append(f"| {t} | {a['engine']} | {a['prefetch']} | {rng([r.get('engine_prompt_tok_s') for r in rows])} | "
                 f"{rng([r.get('ttft_s') for r in rows], 2)} | {rng([r.get('sda4_read_gb') for r in rows], 3)} | "
                 f"{rng([r.get('prefetch_misses') for r in rows], 0)} |")
    o += ["", "## Traced pass (three other slices; perf counts this engine's system calls, ftrace counts ZFS functions on all CPUs)", "",
          "| run | prompt tokens (3 prompts) | madvise calls | fadvise64 calls | zpl_fadvise calls (total ms) | dmu_prefetch calls | dbuf_prefetch calls | prompt tok/s while traced | reads GB per prompt |",
          "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for t in tags:
        x = trace(t)
        if not x:
            continue
        rows = (last(probes, f"{t}-traced") or {}).get("rows", [])
        o.append(f"| {t} | {x['tokens']} | {x['madvise']} | {x['fadvise64']} | {x['zpl_fadvise'][0]} ({x['zpl_fadvise'][1]:.0f}) | "
                 f"{x['dmu_prefetch'][0]} | {x['dbuf_prefetch'][0]} | {rng([r.get('engine_prompt_tok_s') for r in rows])} | "
                 f"{rng([r.get('sda4_read_gb') for r in rows], 3)} |")
    o += ["", "## Perf set headline numbers (run_profile.sh; medians)", "",
          "| run | engine | 1 / 2 / 4 clients total tok/s | 4.4K prompt tok/s [3 runs] | 32K prompt tok/s [3 runs] | 4 users thinking: per-user decode tok/s | 4x16K burst last TTFT s | 16K joins 3 decoders: TTFT s | one-liner during 28K read: TTFT s | Poisson 0.1/s strict goodput | Poisson TTFT p50/p95 s |",
          "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for t in tags:
        a = arm(t)
        sl = R / f"{t}-serve_load.json"
        c = {r["clients"]: r for r in json.loads(sl.read_text())} if sl.exists() else {}
        rep = last(stress, t, "replicate")
        g = lambda k, m: [x.get(m) for x in rep[k]["runs"]] if rep else []   # noqa: E731
        th = last(stress, t, "think4")
        dec = [x.get("client_decode_tok_s") for rd in th["rounds"] for x in rd] if th else []
        fu = jl(R / f"{t}-four_user.jsonl")
        b16 = next((x for x in fu if x["scenario"] == "burst" and x["target_tokens"] == 16384), {})
        ad = next((x for x in fu if x["scenario"] == "admit"), {})
        pe = last(lat, t, "preempt") or {}
        pr = next((r["result"] for r in reversed(lat) if r.get("tag") == t and r.get("scenario") == "poisson"
                   and r["result"].get("rate_req_s") == 0.1), {})   # run_profile.sh's rate
        good = pr.get("goodput_share")
        o.append(f"| {t} | {a['engine']} | {'/'.join(str(round(c[k]['total_tps'], 1)) if k in c else '-' for k in (1, 2, 4))} | "
                 f"{med(g('docs-4.4k', 'engine_prompt_tok_s'))} [{rng(g('docs-4.4k', 'engine_prompt_tok_s'))}] | "
                 f"{med(g('docs-32k', 'engine_prompt_tok_s'))} [{rng(g('docs-32k', 'engine_prompt_tok_s'))}] | {med(dec)} | "
                 f"{b16.get('ttft_last_s', '-')} | {(ad.get('newcomer') or {}).get('ttft_s', '-')} | {(pe.get('short') or {}).get('ttft_s', '-')} | "
                 f"{'-' if good is None else f'{good:.0%}'} | {pr.get('ttft_p50', '-')}/{pr.get('ttft_p95', '-')} |")
    o += ["", "## Runs", "", "| run | arm | engine | exe sha256 | config sha256 |", "|---|---|---|---|---|"]
    for t in tags:
        a = arm(t)
        o.append(f"| {t} | {a['arm']} | {a['engine']} | {a['exe_sha']} | {a['cfg_sha']} |")
    print("\n".join(o))
    return 0


if __name__ == "__main__":
    sys.exit(main())
