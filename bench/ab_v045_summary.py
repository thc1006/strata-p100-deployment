#!/usr/bin/env python3
"""Summarise the 0.1.45 PLE-hint A/B (ab_v045.sh, ab_v045b.sh) into results/AB-0.1.45-ple-hint.md.

Arguments: runs in order, each "tag=label=reference tag" (the reference is the run each per-prompt ratio is taken
against; a run that is its own reference gets 1.000).  Reads results/ple_hint_probe.jsonl, <tag>-arm.txt,
<tag>-t{p,d,p0}-trace.txt and <tag>-m-mem.txt.  Rules (from the review of the first draft):
  - prompts are compared per slice offset (in results/AB-0.1.45-ple-hint.md the three slices differ by ~3% among
    themselves; the arms by less);
  - a row with an error, a prompt row that did not stop at its 32-token limit or read < 15,000 tokens, is left out
    and counted;
  - a count that is missing from a trace prints MISSING, never 0;
  - z-off-1 ran the first probe (no machine-wide CPU, z_rd_int not trusted): those fields print n/a;
  - engine CPU is user + sys of the process (the per-process split is rescaled by the kernel, the sum is exact);
  - answers are compared per tag."""
from __future__ import annotations

import json
import re
import statistics
import sys
from collections import defaultdict
from pathlib import Path

R = Path(__file__).resolve().parents[1] / "results"
PROMPT_OFFS = (777777, 333333, 222222)
DECODE_OFFS = (123456, 654321, 246810)


def load_rows() -> dict:
    by_tag = {}
    for line in (R / "ple_hint_probe.jsonl").read_text().splitlines():
        rec = json.loads(line)
        if rec["tag"] in by_tag:
            if rec["tag"] == "selftest":
                continue
            sys.exit(f"duplicate tag in ple_hint_probe.jsonl: {rec['tag']}")
        by_tag[rec["tag"]] = rec["rows"]
    return by_tag


def valid(r: dict) -> bool:
    if r.get("error"):
        return False
    if r["mode"] == "prompt":
        return r.get("finish") == "length" and (r.get("prompt_tokens") or 0) >= 15000
    return r.get("finish") in ("length", "stop")


def trace(tag: str) -> dict | None:
    p = R / f"{tag}-trace.txt"
    if not p.exists():
        return None
    out = {}
    for line in p.read_text().splitlines():
        m = re.match(r"(\S+)\s+calls\s+(\d+)\s+total\s+([\d.]+) ms\s+mean ([\d.]+) us", line)
        if m:
            out[m[1]] = (int(m[2]), float(m[3]), float(m[4]))
        m = re.match(r"(syscalls:sys_enter_\w+|context-switches|task-clock)\s+([\d.]+)\s*$", line)
        if m:
            out[m[1]] = float(m[2])
    return out


def f1(x, fmt="{:.1f}"):
    return "n/a" if x is None else fmt.format(x)


def mean(xs):
    xs = [x for x in xs if x is not None]
    return statistics.mean(xs) if xs else None


def main() -> int:
    arms = []
    for a in sys.argv[1:]:
        tag, label, ref = (a.split("=") + [None, None])[:3]
        arms.append((tag, label, ref or tag))
    rows = load_rows()
    by = {t: {(r["mode"], r["offset"]): r for r in rows.get(f"{t}-p", []) + rows.get(f"{t}-d", [])} for t, _, _ in arms}
    excluded = {t: [r for k in ("p", "d") for r in rows.get(f"{t}-{k}", []) if not valid(r)] for t, _, _ in arms}
    label = {t: l for t, l, _ in arms}
    md = ["# 0.1.45: the PLE hint on a locked table, and the skip-when-locked patch", "",
          "Generated by `bench/ab_v045_summary.py` from `results/ple_hint_probe.jsonl`, the `*-arm.txt`, "
          "`*-trace.txt` and `*-mem.txt` files.  Every run is a fresh start; the same requests (fixed nonce per slice) go "
          "to every run.", ""]

    md += ["## Runs, in order", "", "| tag | run | engine sha256 | config | VmLck | PLE file | ARC at start | excluded rows |",
           "|---|---|---|---|---|---|---|---|"]
    for t, l, _ in arms:
        a = (R / f"{t}-arm.txt").read_text() if (R / f"{t}-arm.txt").exists() else ""
        g = lambda rx: (re.search(rx, a) or [None, "-"])[1]
        ple = g(r"PLE file mapped: (\S+)")
        sha = g(r"exe \S+ sha256 (\w+)")[:8]
        cfg = Path(g(r"config (\S+) sha256")).name
        lck = g(r"VmLck: (.*)")
        fs = "ext4" if ple.startswith("/mnt/") else "ZFS" if ple != "-" else "(not recorded)"
        arc = g(r"ARC at start: (.*)").strip() if "ARC at start" in a else "(not recorded)"
        md.append(f"| {t} | {l} | {sha} | {cfg} | {lck} | {fs} | {arc} | {len(excluded[t])} |")

    md += ["", "## Fresh ~16K-token prompts, untraced: prefill tok/s per slice (ratio to the reference run)", "",
           "| run | reference | " + " | ".join(f"slice {o}" for o in PROMPT_OFFS) + " | mean ratio | TTFT s | disk GB | ARC prefetch misses |",
           "|---|---|" + "---:|" * (len(PROMPT_OFFS) + 4)]
    for t, l, ref in arms:
        cells, ratios, ttft, disk, miss = [], [], [], [], []
        for o in PROMPT_OFFS:
            r, q = by[t].get(("prompt", o)), by.get(ref, {}).get(("prompt", o))
            if not r or not valid(r):
                cells.append("—"); continue
            x = r["engine_prompt_tok_s"]
            rt = x / q["engine_prompt_tok_s"] if q and valid(q) else None
            ratios.append(rt); ttft.append(r["ttft_s"]); disk.append(r["disk_gb"]); miss.append(r["prefetch_data_misses"])
            cells.append(f"{x:.1f} ({rt:.3f})" if rt else f"{x:.1f}")
        rng = lambda xs, fmt: "—" if not xs else (fmt.format(min(xs)) if fmt.format(min(xs)) == fmt.format(max(xs))
                                                  else f"{fmt.format(min(xs))}–{fmt.format(max(xs))}")
        md.append(f"| {l} | {label.get(ref, ref)} | " + " | ".join(cells) +
                  f" | {f1(mean(ratios), '{:.3f}')} | {rng(ttft, '{:.2f}')} | {rng(disk, '{:.2f}')} | {rng(miss, '{:,}')} |")

    md += ["", "## The same prompts: CPU and memory, mean per prompt", "",
           "Machine-wide figures are /proc/stat over the request (8 vCPUs); z_rd_int is a lower bound (taskq threads that "
           "end mid-request take their time with them); engine = user + sys of the engine process.", "",
           "| run | machine system s | machine user s | iowait s | softirq s | steal s | engine CPU s | z_rd_int s (≥) | arc_evict s | kswapd s | ARC size → end GiB | memory_direct / indirect |",
           "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---|"]
    for t, l, _ in arms:
        rs = [by[t].get(("prompt", o)) for o in PROMPT_OFFS]
        rs = [r for r in rs if r and valid(r)]
        v1 = not rs or "machine_system_s" not in rs[0]
        g = lambda k: None if v1 else mean([r.get(k) for r in rs])
        eng = mean([r["engine_user_s"] + r["engine_sys_s"] for r in rs]) if rs else None
        arc = "n/a" if not rs or rs[-1].get("arc_size_end") is None else f"{rs[-1]['arc_size_end'] / 2**30:.2f}"
        mem = "n/a" if not rs or "memory_direct_count" not in rs[0] else \
            f"{sum(r['memory_direct_count'] for r in rs)} / {sum(r['memory_indirect_count'] for r in rs)}"
        md.append(f"| {l} | {f1(g('machine_system_s'))} | {f1(g('machine_user_s'))} | {f1(g('machine_iowait_s'), '{:.2f}')} | "
                  f"{f1(g('machine_softirq_s'), '{:.2f}')} | {f1(g('machine_steal_s'), '{:.2f}')} | {f1(eng)} | "
                  f"{f1(g('z_rd_int_s'))} | {f1(g('arc_evict_s'), '{:.2f}')} | {f1(g('kswapd_s'), '{:.2f}')} | {arc} | {mem} |")

    md += ["", "## Decode, untraced: engine decode tok/s per request (ratio to the reference run)", "",
           "Same prompt per column in every run (a ~1.5K-token slice to translate, up to 512 tokens out; the answers are "
           "identical across runs, so the drafts accepted are too).", "",
           "| run | " + " | ".join(f"slice {o}" for o in DECODE_OFFS) + " | mean ratio |", "|---|" + "---:|" * (len(DECODE_OFFS) + 1)]
    for t, l, ref in arms:
        cells, ratios = [], []
        for o in DECODE_OFFS:
            r, q = by[t].get(("decode", o)), by.get(ref, {}).get(("decode", o))
            if not r or not valid(r):
                cells.append("—"); continue
            x = r["engine_decode_tok_s"]
            rt = x / q["engine_decode_tok_s"] if q and valid(q) else None
            ratios.append(rt)
            cells.append(f"{x:.1f} ({rt:.3f}, {r['completion_tokens']} tok)" if rt else f"{x:.1f} ({r['completion_tokens']} tok)")
        md.append(f"| {l} | " + " | ".join(cells) + f" | {f1(mean(ratios), '{:.3f}')} |")

    fns = ["do_madvise", "vfs_fadvise", "zpl_fadvise", "dmu_prefetch", "arc_read", "arc_wait_for_eviction",
           "generic_fadvise"]
    for kind, title in (("tp", "Traced prompts: three other slices under perf + ftrace (sleep time counted)"),
                        ("tp0", "Traced prompts, ftrace sleep-time off (time on a CPU only; three more slices)"),
                        ("td", "Traced decodes (two short prompts)")):
        have = [(t, l, trace(f"{t}-{kind}")) for t, l, _ in arms]
        have = [x for x in have if x[2] is not None]
        if not have:
            continue
        md += ["", f"## {title}", "",
               "Function cells: calls / total s / mean µs, on all CPUs (ftrace's function profiler; time includes callees "
               "and the tracer's own cost, so means are higher than untraced).  madvise = the engine's own system calls (perf).", "",
               "| run | tokens in / out | engine madvise | per token in | " + " | ".join(fns) + " |",
               "|---|---:|---:|---:|" + "---:|" * len(fns)]
        for t, l, tr in have:
            rs = rows.get(f"{t}-{kind}", [])
            tin = sum(r.get("prompt_tokens") or 0 for r in rs); tout = sum(r.get("completion_tokens") or 0 for r in rs)
            mad = tr.get("syscalls:sys_enter_madvise")
            cells = ["0" if f not in tr else f"{tr[f][0]:,} / {tr[f][1] / 1000:.2f} / {tr[f][2]:.1f}" for f in fns]
            md.append(f"| {l} | {tin:,} / {tout:,} | {'MISSING' if mad is None else f'{mad:,.0f}'} | "
                      f"{'—' if mad is None or not tin else f'{mad / tin:.2f}'} | " + " | ".join(cells) + " |")
        md.append("")
        md.append("A function with no line in the profiler's output was not called (0); a perf count that is absent prints MISSING.")

    mems = [(t, l, R / f"{t}-m-mem.txt") for t, l, _ in arms if (R / f"{t}-m-mem.txt").exists()]
    if mems:
        md += ["", "## Where the hint's time goes (kprobes on the engine's threads only, a separate pass)", ""]
        for t, l, p in mems:
            body = p.read_text()
            part = body.split("--- perf script | mem_parse.py", 1)[-1].split("--- perf script stderr", 1)[0].strip()
            rec = body.split("--- perf record stderr", 1)[-1].split("--- perf script | mem_parse.py", 1)[0].strip()
            md += [f"**{l}** (`{p.name}`)", "", "```", part, "", "perf record: " + " ".join(rec.split())[:300], "```", ""]

    md += ["", "## Answers: byte-identical across runs?", ""]
    keys = defaultdict(dict)
    for t, _, _ in arms:
        for kind in ("p", "d", "tp", "td", "tp0", "m-mem"):
            for r in rows.get(f"{t}-{kind}", []):
                keys[(r["mode"], r["offset"])][t] = r["text_sha"]
    same = [k for k, m in keys.items() if len(set(m.values())) == 1]
    md.append(f"{len(same)} of {len(keys)} requests gave the same text (sha256) in every run that sent them.")
    for (mode, off), m in sorted(keys.items()):
        if len(set(m.values())) > 1:
            md.append(f"- DIFFERS: {mode} {off}: {json.dumps(m)}")
    md += ["", "## Excluded rows", ""]
    for t, _, _ in arms:
        for r in excluded[t]:
            md.append(f"- {t}: {r['mode']} {r['offset']}: error {r.get('error')!r}, finish {r.get('finish')}, "
                      f"prompt tokens {r.get('prompt_tokens')}")
    if not any(excluded.values()):
        md.append("None.")
    (R / "AB-0.1.45-ple-hint.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
