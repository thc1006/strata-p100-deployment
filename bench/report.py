#!/usr/bin/env python3
"""One comparison table per metric family, straight from the raw result files (no numbers typed by hand).

  python3 bench/report.py [results-dir] > results/SUMMARY.md
"""
from __future__ import annotations

import json
import math
import statistics
import sys
from pathlib import Path

R = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "results"
ORDER = ["baseline", "R1-pleram", "R1b-noplepf", "R3-groups1", "R2-lastlight", "R4-pr2050-p8192", "R2-final-AA",
         "final-cold", "final", "final-parking", "exp-prefill4096", "exp-prefill1024", "deployed",
         "v431-1", "v441-1", "v441pf", "v441-2", "v431-2"]
# replicate before the fix re-read the same text 3 times (warm pages on PLE mmap); from final-cold on, the 3 runs read 3
# different slices (run 1's slice is the one every earlier config read; final-cold's 32K slices start where its 4.4K
# slices start, later configs' do not; from final-parking on every config reads the same three slices).  Every request
# starts with a random nonce, so no run reuses another's prefix.  Any tag not listed here is a three-slice run.
REPLICATE_SAME_TEXT = {"baseline", "R1-pleram", "R1b-noplepf", "R3-groups1", "R2-lastlight", "R4-pr2050-p8192", "R2-final-AA"}
LABEL = {"baseline": "R0 baseline (PLE mmap, 12/24/36)", "R1-pleram": "R1 PLE ram",
         "R1b-noplepf": "R1b PLE ram + --no-ple-prefetch", "R3-groups1": "R3 R1b + batch-groups 1",
         "R2-lastlight": "R2 R1b + split 13/26/38", "R4-pr2050-p8192": "R4 R2 + PR #2050 piece 8192",
         "R2-final-AA": "R2 again (A/A, fresh restart)", "final-cold": "R2 + batch-groups auto, no parking (first run)",
         "final": "R2 + batch-groups auto, no parking",
         "final-parking": "DEPLOYED except min-free (perf set; parking floor 2560 MiB)",
         "exp-prefill4096": "deployed with --prefill 4096", "exp-prefill1024": "deployed with --prefill 1024",
         "deployed": "DEPLOYED (exact config, sha256 9d774535...)",
         "v431-1": "A/B: 0.1.43.1 deployed, run 1", "v441-1": "A/B: 0.1.44.1 same config, run 1",
         "v441pf": "A/B: 0.1.44.1 without --no-ple-prefetch", "v441-2": "A/B: 0.1.44.1 same config, run 2",
         "v431-2": "A/B: 0.1.43.1 deployed, run 2"}


def jl(p: Path) -> list[dict]:
    return [json.loads(x) for x in p.read_text().splitlines() if x.strip()] if p.exists() else []


def last(recs, tag, scen):
    m = [r for r in recs if r.get("tag") == tag and r.get("scenario") == scen]
    return m[-1]["result"] if m else None


def pct(xs, p):
    """Nearest-rank percentile, as bench/latency_suite.py computes it now.  Poisson rows are recomputed with it because
    the first six runs (R1 to R2 A/A) stored an upper median as p50."""
    xs = sorted(x for x in xs if x is not None)
    return round(xs[max(0, math.ceil(p * len(xs)) - 1)], 2) if xs else None


def f(x, nd=1):
    return "-" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def median_or_none(xs):
    xs = [x for x in xs or [] if x is not None]
    return statistics.median(xs) if xs else None


def rng(xs, nd=1):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "-"
    return f"{statistics.median(xs):.{nd}f} [{min(xs):.{nd}f}-{max(xs):.{nd}f}]"


def main() -> int:
    stress, lat = jl(R / "stress.jsonl"), jl(R / "latency.jsonl")
    seen = [r.get("tag") for r in stress + lat]
    tags = [t for t in ORDER if t in seen] + [t for t in dict.fromkeys(seen) if t and t not in ORDER]
    for t in tags:
        LABEL.setdefault(t, t)
    out = ["# Results summary (generated by bench/report.py from the raw files)", ""]

    out += ["## serve_load (short prompts, 512 tokens, thinking off; median of 3 rounds)", "",
            "| config | 1 client total | 2 clients total | 4 clients total | 4 clients per request | 4 clients TTFT p50/p95 | errors |",
            "|---|---:|---:|---:|---:|---:|---:|"]
    for t in tags:
        p = R / ("baseline-serve_load.json" if t == "baseline" else f"{t}-serve_load.json")
        if not p.exists():
            continue
        rows = {r["clients"]: r for r in json.loads(p.read_text())}
        c4 = rows.get(4, {})
        out.append(f"| {LABEL[t]} | {f(rows.get(1, {}).get('total_tps'))} | {f(rows.get(2, {}).get('total_tps'))} | "
                   f"{f(c4.get('total_tps'))} | {f(c4.get('per_req_tps'))} | {f(c4.get('first_p50'), 2)}/{f(c4.get('first_p95'), 2)} s | "
                   f"{sum(r.get('errors', 0) for r in rows.values())} |")

    out += ["", "## Community-report method (reasoning off, 256 tokens; engine timings, median [range] of 3 fresh-nonce runs)", "",
            "Rows marked (same text) re-read one text 3 times with only a new nonce, so on a PLE-mmap config runs 2-3 read "
            "warm pages and the range's low end is the cold run; rows marked (new text) read three different slices (the same "
            "three in every config from final-parking on). On configs with conversation parking, the engine's prompt time "
            "of runs 2-3 (4.4K) and all 32K runs includes parking the previous conversation (the engine log's "
            "'conversation cache: parked' line just before each; see engine-log-20261016-extract.txt).", "",
            "| config | docs ~4.4K prompt tok/s | docs ~32K prompt tok/s | docs ~32K TTFT s | reasoning-v1 decode tok/s | code-v1 decode tok/s |",
            "|---|---:|---:|---:|---:|---:|"]
    for t in tags:
        r = last(stress, t, "replicate")
        if not r:
            continue
        g = lambda k, m: [x.get(m) for x in r[k]["runs"]]   # noqa: E731
        how = "same text" if t in REPLICATE_SAME_TEXT else "new text"
        out.append(f"| {LABEL[t]} ({how}) | {rng(g('docs-4.4k', 'engine_prompt_tok_s'))} | {rng(g('docs-32k', 'engine_prompt_tok_s'))} | "
                   f"{rng(g('docs-32k', 'ttft_s'))} | {rng(g('reasoning-v1', 'engine_decode_tok_s'))} | {rng(g('code-v1', 'engine_decode_tok_s'))} |")

    out += ["", "## Four users with thinking (medium, budget 1024, max_tokens 4096; 3 rounds x 4 users)", "",
            "| config | per-user decode tok/s median [range] | request wall time s median [range] | errors |", "|---|---:|---:|---:|"]
    for t in tags:
        r = last(stress, t, "think4")
        if not r:
            continue
        reqs = [x for rd in r["rounds"] for x in rd]
        out.append(f"| {LABEL[t]} | {rng([x.get('client_decode_tok_s') for x in reqs])} | {rng([x.get('total_s') for x in reqs])} | "
                   f"{sum(1 for x in reqs if x.get('status') != 200 or x.get('error'))} |")

    out += ["", "## Long prompts arriving together (TTFT of the first / last admission)", "",
            "| config | 4 x 8K first/last s | 4 x 16K first/last s | 4 x 27K first/last s | 16K joins 3 decoders: its TTFT s | decoders' rate during that admission tok/s |",
            "|---|---:|---:|---:|---:|---:|"]
    for t in tags:
        fu = jl(R / ("four_user.jsonl" if t == "baseline" else f"{t}-four_user.jsonl"))
        b8 = next((x for x in fu if x["scenario"] == "burst" and x["target_tokens"] == 8192), {})
        b16 = next((x for x in fu if x["scenario"] == "burst" and x["target_tokens"] == 16384), {})
        ad = next((x for x in fu if x["scenario"] == "admit"), {})
        w = last(stress, t, "worst") or {}
        if not (b8 or b16 or ad or w):
            continue
        out.append(f"| {LABEL[t]} | {f(b8.get('ttft_first_s'))}/{f(b8.get('ttft_last_s'))} | {f(b16.get('ttft_first_s'))}/{f(b16.get('ttft_last_s'))} | "
                   f"{f(w.get('ttft_first_s'))}/{f(w.get('ttft_last_s'))} | {f((ad.get('newcomer') or {}).get('ttft_s'))} | "
                   f"{f(median_or_none(ad.get('decoder_stream_rate_during_admission')), 2)} |")

    out += ["", "## Stalls and preemption (upstream #2050 / #2326 metrics)", "",
            "| config | cold join: decoders' longest pause s | joiners' TTFT s | one-liner 1 s into a 28K read: TTFT / done s | the 28K read's TTFT s |",
            "|---|---:|---:|---:|---:|"]
    for t in tags:
        cj, pe = last(lat, t, "coldjoin"), last(lat, t, "preempt")
        if not cj and not pe:
            continue
        cj, pe = cj or {}, pe or {}
        out.append(f"| {LABEL[t]} | {'/'.join(f(d.get('longest_pause_s')) for d in cj.get('decoders', []))} | "
                   f"{'/'.join(f(j.get('ttft_s')) for j in cj.get('joiners', []))} | {f((pe.get('short') or {}).get('ttft_s'))} / {f((pe.get('short') or {}).get('total_s'))} | "
                   f"{f((pe.get('long') or {}).get('ttft_s'))} |")

    out += ["", "## Open-loop Poisson arrivals (same seeded request sequence for every config)", "",
            "SLO fixed before the runs: TTFT <= 10 s + prompt_tokens/400, longest pause <= 10 s, decode >= 5 tok/s. "
            "'loose' = TTFT <= 30 s + prompt_tokens/300 and pause <= 30 s.", "",
            "| config | rate req/s | n | goodput strict | goodput loose | TTFT p50/p95 s | longest pause p95/max s | errors |",
            "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for r in lat:
        if r["scenario"] != "poisson":
            continue
        x = r["result"]
        rows = x["rows"]
        loose = sum(1 for y in rows if y.get("ttft_s") is not None and y["ttft_s"] <= 30 + (y.get("prompt_tokens") or 0) / 300
                    and (y.get("longest_pause_s") or 0) <= 30) / len(rows)
        out.append(f"| {LABEL.get(r['tag'], r['tag'])} | {x['rate_req_s']} | {x['requests']} | {x['goodput_share']:.0%} | {loose:.0%} | "
                   f"{f(pct([y.get('ttft_s') for y in rows], .5))}/{f(pct([y.get('ttft_s') for y in rows], .95))} | "
                   f"{f(pct([y.get('longest_pause_s') for y in rows], .95))}/{f(x['longest_pause_max'])} | {x['errors']} |")

    out += ["", "## Resources over each config's whole run (monitor.py)", "",
            "disk reads: the whole disk (sda) for R1b through the A/A run, the pool partition (sda4) from final-cold on; "
            "R0 and R1 have no disk column (R1's separate whole-disk monitor is R1-pleram-disk.csv).", "",
            "| config | min free VRAM per card MiB | mean GPU util % | min MemAvailable GiB | max swap used GiB | disk reads GB |",
            "|---|---:|---:|---:|---:|---:|"]
    for t in tags:
        p = R / f"{t}-monitor-all.json"
        if not p.exists():
            continue
        m = json.loads(p.read_text())
        out.append(f"| {LABEL[t]} | {'/'.join(str(m[f'gpu{i}']['min_free_mib']) for i in range(4))} | "
                   f"{'/'.join(str(m[f'gpu{i}']['mean_util_pct']) for i in range(4))} | {m['host']['min_mem_avail_gib']} | "
                   f"{m['host']['swap_used_max_gib']} | {f((m.get('storage') or {}).get('disk_read_gb'), 2)} |")
    out += ["", "## Resources during the robustness runs (monitor.py, whole run)", "",
            "| config | CPU mean busy % cpu0..7 | min MemAvailable GiB | engine RSS start/max GiB | max swap used GiB | "
            "disk / swap-in reads GB | max GPU temp C | throttle |", "|---|---|---:|---:|---:|---:|---:|---|"]
    for rtag in ("final", "deployed"):
        p = R / f"{rtag}-robust-monitor-all.json"
        if not p.exists():
            continue
        m = json.loads(p.read_text())
        h, st = m["host"], m.get("storage") or {}
        cpu = "/".join(f"{v:.0f}" for v in (m.get("cpu_mean_busy_pct") or {}).values()) or "-"
        names = {"0x0000000000000001": "idle", "0x0000000000000004": "SW power cap", "0x0000000000000008": "HW slowdown",
                 "0x0000000000000020": "SW thermal", "0x0000000000000040": "HW thermal", "0x0000000000000080": "power brake"}
        thr = sorted({names.get(x, x) for i in range(4) for x in m[f"gpu{i}"].get("throttle_reasons_seen", [])} - {"idle"})
        out.append(f"| {LABEL.get(rtag, rtag)} | {cpu} | {h['min_mem_avail_gib']} | {h.get('engine_rss_start_gib')}/"
                   f"{h.get('engine_rss_max_gib')} | {h['swap_used_max_gib']} | {f(st.get('disk_read_gb'), 2)} / "
                   f"{f(st.get('swap_in_gb'), 3)} | {max(m[f'gpu{i}']['max_temp_c'] for i in range(4))} | {', '.join(thr) or 'none'} |")
    out += ["", "## Multi-turn conversations, 6 clients on 4 slots (cached prompt tokens and TTFT per turn)", ""]
    for t in ("final", "R5-parking", "final-deployed-mt"):
        r = last(stress, t, "multiturn")
        if not r:
            continue
        lab = {"final": "without parking", "R5-parking": "with parking (min-free default)", "final-deployed-mt": "deployed (parking, min-free 8192)"}[t]
        for i, (c, tt) in enumerate(zip(r["cached_tokens_by_turn"], r["ttft_by_turn"])):
            out.append(f"- {lab}, conversation {i}: cached {c}, TTFT s {tt}")
    for rtag in ("final", "deployed"):
      out += ["", f"## Robustness: {LABEL.get(rtag, rtag)} (tag {rtag})", ""]
      for scen in ("boundary", "disconnect", "multiturn", "budget", "qa", "soak"):
        r = last(stress, rtag, scen)
        if not r:
            continue
        if scen == "boundary":
            line = (f"prompt {r.get('prompt_tokens')} tok, room {r.get('room')}: one token over -> {r.get('over_by_one_status')}, "
                    f"exact fit -> {r.get('exact_fit_status')}; pass {r.get('pass')}")
        elif scen == "disconnect":
            line = (f"others finished {[x.get('completion_tokens') for x in r.get('others', [])]} tokens, fifth request TTFT "
                    f"{(r.get('fifth_after') or {}).get('ttft_s')} s; pass {r.get('pass')}")
        elif scen == "multiturn":
            line = (f"{r.get('turns')} turns + {r.get('extra_requests')} extra requests, {r.get('failures')} failures; "
                    f"cached tokens by turn {r.get('cached_tokens_by_turn')}")
        elif scen == "budget":
            line = "; ".join(f"budget {x['budget']}: {x.get('reasoning_chunks')} reasoning chunks, answer {x.get('answer')} "
                             f"(want {x['want']})" for x in r.get("rows", []))
        elif scen == "qa":
            line = f"solo {r.get('solo_correct')}/{r.get('n')}, four at a time {r.get('concurrent_correct')}/{r.get('n')}"
        else:
            kinds = ", ".join(f"{k} n={v.get('n')} TTFT p50/max {f(v.get('ttft_p50'), 2)}/{f(v.get('ttft_max'), 2)} s"
                              for k, v in (r.get("by_kind") or {}).items())
            line = (f"{r.get('minutes')} min x {r.get('clients')} clients: {r.get('requests')} requests, {r.get('errors')} errors, "
                    f"{r.get('generated_tokens')} tokens; {kinds}")
        out.append(f"- **{scen}**: {line}")
      q = R / f"{rtag}-overload.json"
      if q.exists():
          out.append("- **overload (more clients than the 4 slots)**: " + "; ".join(
              f"{x.get('clients')} clients: total {f(x.get('total_tps'))} tok/s, TTFT p50/p95 {f(x.get('first_p50'), 2)}/"
              f"{f(x.get('first_p95'), 2)} s, errors {x.get('errors')}" for x in json.loads(q.read_text())))
      q = R / f"{rtag}-needles.json"
      if q.exists():
          ns = json.loads(q.read_text())
          out.append(f"- **needle**: {sum(1 for x in ns if x.get('found'))}/{len(ns)} found (" + ", ".join(
              f"{x.get('length')} depth {x.get('depth')}%: {x.get('prompt_tokens')} tok, {'found' if x.get('found') else 'MISSED'}"
              for x in ns) + ")")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
